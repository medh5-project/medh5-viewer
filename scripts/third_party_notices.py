#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES: the licences of everything the app links.

The app statically links the medh5 engine and, through it, Rust crates and
C libraries (HDF5, C-Blosc2, LZ4, Zstandard, zlib). This reads the bridge's
dependency graph with `cargo metadata` and collects, for every package that
ends up in the static library, its declared licence and the licence files it
ships; the C libraries' licences come from the -sys crates that vendor them.

    python3 -I scripts/third_party_notices.py            # write THIRD_PARTY_NOTICES
    python3 -I scripts/third_party_notices.py --check    # fail if it is stale
"""

from __future__ import annotations

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES"
LICENSE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT")
# C libraries vendored inside -sys crates, by the crate that carries them and
# the relative paths of their licence files (whichever exist).
VENDORED = {
    "hdf5-metno-src": ("HDF5", ["ext/hdf5/LICENSE", "ext/hdf5/COPYING"]),
    "medh5-sys": (
        "C-Blosc2, the codecs it bundles, and the HDF5-Blosc2 filter",
        ["vendor/c-blosc2/LICENSE.txt",
         "vendor/c-blosc2/LICENSES/BITSHUFFLE.txt",
         "vendor/c-blosc2/LICENSES/FASTLZ.txt",
         "vendor/hdf5-blosc2/LICENSE.txt"],
    ),
    "lz4-sys": ("LZ4", ["liblz4/LICENSE", "liblz4/lib/LICENSE"]),
    "zstd-sys": ("Zstandard", ["zstd/LICENSE", "zstd/COPYING"]),
    "libz-sys": ("zlib", ["src/zlib/LICENSE", "src/zlib/README"]),
}


def metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--manifest-path", str(ROOT / "bridge" / "Cargo.toml"),
         "--filter-platform", "aarch64-apple-darwin"],
        check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def linked_packages(meta: dict) -> list[dict]:
    """Packages reachable from the bridge through normal (not dev/build) edges."""
    by_id = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen: set[str] = set()
    stack = [root]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            kinds = {k.get("kind") for k in dep["dep_kinds"]}
            if None in kinds or "normal" in kinds:
                stack.append(dep["pkg"])
    seen.discard(root)
    return sorted((by_id[p] for p in seen), key=lambda p: (p["name"].lower(), p["version"]))


def licence_files(directory: pathlib.Path) -> list[pathlib.Path]:
    files = []
    for path in sorted(directory.iterdir()):
        if path.is_file() and path.name.upper().startswith(LICENSE_NAMES):
            files.append(path)
    return files


def texts_of(p: dict) -> list[tuple[str, str]]:
    """(label, text) of every licence file a package ships or vendors."""
    directory = pathlib.Path(p["manifest_path"]).parent
    found = [(str(path.relative_to(directory)), path) for path in licence_files(directory)]
    if p["name"] in VENDORED:
        what, rels = VENDORED[p["name"]]
        for rel in rels:
            candidate = directory / rel
            if candidate.is_file():
                found.append((f"{what}: {rel}", candidate))
    return [(label, path.read_text(encoding="utf-8", errors="replace").strip()) for label, path in found]


def render(packages: list[dict]) -> str:
    lines = [
        "THIRD-PARTY NOTICES",
        "",
        "medh5 Viewer statically links the medh5 engine and the software listed",
        "below. Each is distributed under its licence; every distinct licence",
        "text is reproduced once, after the list of the packages it covers.",
        "Generated by scripts/third_party_notices.py from bridge/Cargo.lock.",
        "",
        "PACKAGES",
        "",
    ]
    by_text: dict[str, list[str]] = {}
    for p in packages:
        name = f"{p['name']} {p['version']}"
        lines.append(f"  {name} — {p.get('license') or 'see its licence below'}"
                     + (f" ({p['repository']})" if p.get("repository") else ""))
        for label, text in texts_of(p):
            by_text.setdefault(text, []).append(f"{name} ({label})")
    lines.append("")
    for text, users in by_text.items():
        lines.append("=" * 78)
        for user in users:
            lines.append(user)
        lines.append("=" * 78)
        lines.append("")
        lines.append(text)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = render(linked_packages(metadata()))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("THIRD_PARTY_NOTICES is stale: run scripts/third_party_notices.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
